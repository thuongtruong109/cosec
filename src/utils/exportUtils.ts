/**
 * Draws and downloads a crisp PNG scorecard badge directly to canvas
 */
export function generateScorecardImage(
  analysis: AnalysisResult,
  theme: 'cyber' | 'obsidian' | 'emerald' = 'cyber'
): Promise<Blob> {
  return new Promise((resolve, reject) => {
    const canvas = document.createElement('canvas');
    const ctx = canvas.getContext('2d');
    if (!ctx) {
      reject(new Error('Canvas context not available'));
      return;
    }

    const width = 1200;
    const height = 675; // 16:9 ratio crisp banner
    canvas.width = width;
    canvas.height = height;

    // Palette setups
    let bgGradientStart = '#09090b';
    let bgGradientEnd = '#13111c';
    let accentColor = '#6366f1';
    let accentLight = '#818cf8';

    if (theme === 'obsidian') {
      bgGradientStart = '#0f0c1b';
      bgGradientEnd = '#1d1238';
      accentColor = '#a855f7';
      accentLight = '#c084fc';
    } else if (theme === 'emerald') {
      bgGradientStart = '#061a14';
      bgGradientEnd = '#020b08';
      accentColor = '#10b981';
      accentLight = '#34d399';
    }

    // 1. Background Fill
    const bgGrad = ctx.createLinearGradient(0, 0, width, height);
    bgGrad.addColorStop(0, bgGradientStart);
    bgGrad.addColorStop(1, bgGradientEnd);
    ctx.fillStyle = bgGrad;
    ctx.fillRect(0, 0, width, height);

    // 2. Subtle Grid overlay
    ctx.strokeStyle = 'rgba(255, 255, 255, 0.04)';
    ctx.lineWidth = 1;
    const gridSize = 40;
    for (let x = 0; x < width; x += gridSize) {
      ctx.beginPath();
      ctx.moveTo(x, 0);
      ctx.lineTo(x, height);
      ctx.stroke();
    }
    for (let y = 0; y < height; y += gridSize) {
      ctx.beginPath();
      ctx.moveTo(0, y);
      ctx.lineTo(width, y);
      ctx.stroke();
    }

    // 3. Glowing Ambient Blobs
    const blobGrad = ctx.createRadialGradient(width * 0.25, height * 0.5, 10, width * 0.25, height * 0.5, 300);
    blobGrad.addColorStop(0, 'rgba(99, 102, 241, 0.18)');
    blobGrad.addColorStop(1, 'rgba(0, 0, 0, 0)');
    ctx.fillStyle = blobGrad;
    ctx.fillRect(0, 0, width, height);

    // 4. Outer Border
    ctx.strokeStyle = 'rgba(255, 255, 255, 0.12)';
    ctx.lineWidth = 2;
    ctx.strokeRect(30, 30, width - 60, height - 60);

    // 5. Header: Logo & Title
    ctx.fillStyle = accentLight;
    ctx.font = 'bold 16px "SF Pro Display", -apple-system, sans-serif';
    ctx.fillText('CODELENS AI • SENIOR CODE REVIEW AUDIT', 60, 80);

    ctx.fillStyle = '#ffffff';
    ctx.font = 'bold 38px "SF Pro Display", -apple-system, sans-serif';
    ctx.fillText(analysis.projectName, 60, 130);

    const dateStr = new Date(analysis.analyzedAt).toLocaleDateString('en-US', {
      year: 'numeric',
      month: 'short',
      day: 'numeric',
    });
    ctx.fillStyle = '#a1a1aa';
    ctx.font = '16px monospace';
    ctx.fillText(`Audited on ${dateStr}  •  ${analysis.totalFiles} Files  •  ${analysis.totalLines.toLocaleString()} Lines`, 60, 165);

    // 6. Score Circle (Left-Center)
    const centerX = 260;
    const centerY = 390;
    const radius = 130;

    // Outer track
    ctx.beginPath();
    ctx.arc(centerX, centerY, radius, 0, Math.PI * 2);
    ctx.strokeStyle = '#27272a';
    ctx.lineWidth = 18;
    ctx.stroke();

    // Health Arc
    const scoreFrac = Math.min(Math.max(analysis.scores.overall / 100, 0), 1);
    const startAngle = -Math.PI / 2;
    const endAngle = startAngle + scoreFrac * Math.PI * 2;

    ctx.beginPath();
    ctx.arc(centerX, centerY, radius, startAngle, endAngle);
    ctx.strokeStyle = accentLight;
    ctx.lineWidth = 18;
    ctx.lineCap = 'round';
    ctx.stroke();

    // Score Text Inside Circle
    ctx.fillStyle = '#ffffff';
    ctx.font = 'bold 64px "SF Pro Display", -apple-system, sans-serif';
    ctx.textAlign = 'center';
    ctx.fillText(`${analysis.scores.overall}`, centerX, centerY + 12);

    ctx.fillStyle = '#a1a1aa';
    ctx.font = 'bold 14px monospace';
    ctx.fillText('/ 100 HEALTH', centerX, centerY + 45);

    // 7. Right Metrics Grid
    ctx.textAlign = 'left';
    const startX = 480;
    const metricsY = 220;

    const subMetrics = [
      { name: 'Security & Auth', score: analysis.scores.security, color: '#f43f5e' },
      { name: 'Reliability & Bugs', score: analysis.scores.reliability, color: '#10b981' },
      { name: 'Performance & Leaks', score: analysis.scores.performance, color: '#f59e0b' },
      { name: 'Maintainability', score: analysis.scores.maintainability, color: '#818cf8' },
      { name: 'Architecture Coupling', score: analysis.scores.architecture, color: '#a855f7' },
    ];

    subMetrics.forEach((m, idx) => {
      const y = metricsY + idx * 62;
      // Label
      ctx.fillStyle = '#e4e4e7';
      ctx.font = '600 17px "SF Pro Display", -apple-system, sans-serif';
      ctx.fillText(m.name, startX, y);

      // Score
      ctx.fillStyle = m.color;
      ctx.font = 'bold 18px monospace';
      ctx.fillText(`${m.score}/100`, startX + 530, y);

      // Progress bar background
      ctx.fillStyle = '#27272a';
      ctx.fillRect(startX, y + 10, 600, 8);

      // Progress bar fill
      ctx.fillStyle = m.color;
      ctx.fillRect(startX, y + 10, (600 * m.score) / 100, 8);
    });

    // 8. Bottom Bar: Issues Summary
    const footerY = 590;
    ctx.fillStyle = '#18181b';
    ctx.fillRect(60, 530, width - 120, 75);
    ctx.strokeStyle = '#27272a';
    ctx.lineWidth = 1;
    ctx.strokeRect(60, 530, width - 120, 75);

    ctx.fillStyle = '#f43f5e';
    ctx.font = 'bold 16px monospace';
    ctx.fillText(`🚨 ${analysis.issueCounts.critical} CRITICAL`, 90, 574);

    ctx.fillStyle = '#f97316';
    ctx.font = 'bold 16px monospace';
    ctx.fillText(`⚠️ ${analysis.issueCounts.high} HIGH`, 310, 574);

    ctx.fillStyle = '#eab308';
    ctx.font = 'bold 16px monospace';
    ctx.fillText(`⚡ ${analysis.issueCounts.medium} MEDIUM`, 510, 574);

    ctx.fillStyle = '#10b981';
    ctx.font = 'bold 16px monospace';
    ctx.fillText(`✅ AI FIXES READY`, 750, 574);

    ctx.fillStyle = '#71717a';
    ctx.font = '12px monospace';
    ctx.textAlign = 'right';
    ctx.fillText('VERIFIED BY CODELENS', width - 90, 574);

    canvas.toBlob((blob) => {
      if (blob) {
        resolve(blob);
      } else {
        reject(new Error('Failed to generate canvas image blob'));
      }
    }, 'image/png');
  });
}
