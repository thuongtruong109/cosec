/**
 * Generates a clean CSV file of all detected issues
 */
export function generateCSVReport(analysis: AnalysisResult): string {
  const headers = ['ID', 'Severity', 'Category', 'Title', 'File', 'Line', 'CWE', 'Confidence', 'Description', 'Suggested Fix'];
  
  const rows = analysis.issues.map((i) => [
    `"${i.id}"`,
    `"${i.severity}"`,
    `"${i.category}"`,
    `"${i.title.replace(/"/g, '""')}"`,
    `"${i.file}"`,
    i.line,
    `"${i.cwe || 'N/A'}"`,
    `"${(i.confidence * 100).toFixed(0)}%"`,
    `"${i.description.replace(/"/g, '""')}"`,
    `"${(i.suggestedFix || '').replace(/"/g, '""')}"`,
  ]);

  return [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
}

